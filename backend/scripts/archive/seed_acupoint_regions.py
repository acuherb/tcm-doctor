ORDER = ["腰骶", "后背", "前胸", "上肢", "下肢", "头面"]


def infer(name: str, location: str | None):
    text = f"{(location or '')} {name}"
    for region in ORDER:
        for kw in KW[region]:
            if kw in text:
                return region
    return None


def main():
    apply = "--apply" in sys.argv
    conn = sqlite3.connect(DB)
    rows = conn.execute("SELECT id, name, meridian, location, region FROM acupoints").fetchall()
    filled = []      # (name, region)
    skipped = []     # (name, meridian) 无法推断
    kept = 0
    for _id, name, meridian, location, region in rows:
        if region:
            kept += 1
            continue
        r = infer(name, location)
        if r:
            filled.append((name, r))
            if apply:
                conn.execute("UPDATE acupoints SET region=? WHERE id=?", (r, _id))
        else:
            skipped.append((name, meridian))
    if apply:
        conn.commit()
    conn.close()

    from collections import Counter
    cnt = Counter(r for _, r in filled)
    print(f"现有已带 region: {kept}")
    print(f"本次将补全: {len(filled)}  (按部位: {dict(cnt)})")
    print(f"无法推断(留空, 需手动补): {len(skipped)}")
    print("\n=== 补全样例(前 15) ===")
    for n, r in filled[:15]:
        print(f"  {n} -> {r}")
    if skipped:
        print("\n=== 留空列表(供手动补) ===")
        for n, m in skipped:
            print(f"  {n}  [{m}]")
    if apply:
        total = sqlite3.connect(DB).execute("SELECT COUNT(*) FROM acupoints WHERE region<>'' ").fetchone()[0]
        print(f"\n[APPLY] 库内带 region 的穴位总数: {total}")


if __name__ == "__main__":
    main()
